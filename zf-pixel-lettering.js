function glyphFor(letter){
 const normalized=letter.normalize('NFD').replace(/[\u0300-\u036f]/g,'');
 return pixels[normalized]||pixels[' '];
}
function draw(ctx,text,x,y,options={}){
 const align=options.align||'left', tone=options.tone||'gold';
 const scale=Number(options.scale)||1, maxWidth=options.maxWidth||320;
 const variant=options.variant||'title';
 const textValue=String(text).toUpperCase();
 const letters=Array.from(textValue);
 const advance=variant==='compact'?7:8;
 const w=letters.length*advance-1;
 const zoom=Math.min(scale,maxWidth/Math.max(1,w));
 const total=w*zoom;
 ctx.save();ctx.imageSmoothingEnabled=false;
 ctx.translate(Math.round(x-(align==='center'?total/2:align==='right'?total:0)),Math.round(y));
 ctx.scale(zoom,zoom);
 const palette=tone==='blue'
  ?{shadow:'#010d42',rim:'#0762a7',light:'#a3ffff',face:'#41d4ff',dark:'#2087dd'}
  :tone==='cream'
  ?{shadow:'#000821',rim:'#786c81',light:'#ffffff',face:'#dfdbe2',dark:'#a1a7bf'}
  :{shadow:'#170821',rim:'#a53c29',light:'#fff7ae',face:'#ffd064',dark:'#e97939'};
 letters.forEach((letter,i)=>{
  const bits=glyphFor(letter),gx=i*advance;
  // La version "title" comporte des empattements de tuile, sans police OS.
  const data=[];
  for(let yy=0;yy<9;yy++)for(let xx=0;xx<7;xx++){
   if(bits[yy][xx]==='1')data.push([xx,yy]);
  }
  if(variant==='title'&&/[A-Z]/.test(letter)){
   // Empattements rectangulaires communs aux capitales SFII SNES.
   const stemTop=[...Array(7).keys()].filter(xx=>bits[0][xx]==='1');
   const stemBase=[...Array(7).keys()].filter(xx=>bits[8][xx]==='1');
   for(const xx of [...stemTop,...stemBase]){
    const yy=stemTop.includes(xx)?0:8;
    if(xx>0)data.push([xx-1,yy]);
    if(xx<6)data.push([xx+1,yy]);
   }
  }
  for(const [xx,yy] of data){
   ctx.fillStyle=palette.shadow;ctx.fillRect(gx+xx+1,yy+2,1,1);
   ctx.fillStyle=palette.rim;ctx.fillRect(gx+xx+1,yy+1,1,1);
   ctx.fillStyle=yy<2?palette.light:yy<6?palette.face:palette.dark;
   ctx.fillRect(gx+xx,yy,1,1);
  }
  if(/[ÉÈÊ]/.test(letter)){
   ctx.fillStyle=palette.light;ctx.fillRect(gx+3,-2,2,1);
  }
 });
 ctx.restore();
 return total;
}
function lines(text,maxChars=18){
 const words=String(text).toUpperCase().split(/\s+/);const out=[];
 let current='';
 for(const word of words){
  if(current&&current.length+1+word.length>maxChars){out.push(current);current=word;}
  else current+=(current?' ':'')+word;
 }
 if(current)out.push(current);
 return out;
}
